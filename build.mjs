import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
const windRoot = join(root, '..', 'WindUI');
// Git's Windows checkout settings must not change a release revision or digest.
const readText = path => readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
const core = readText(join(root, 'src/core.lua'));
const main = readText(join(root, 'src/main.lua'));
const wind = readText(join(windRoot, 'dist/main.lua'));
const license = readText(join(windRoot, 'LICENSE'));
const bundle = main.replace('__CLARIS_CORE__', `(function()\n${core}\nend)()`);
if (bundle.includes('__CLARIS_CORE__')) throw new Error('Unresolved bundle marker');
const digest = data => createHash('sha256').update(data).digest('hex');
const revision = digest(bundle + '\n' + wind).slice(0, 20);
const repo = 'https://raw.githubusercontent.com/Clarissv/Claris-Growblox-Autofarm/main/';
const base = `${repo}releases/${revision}/`;
const loader = `-- Claris Growblox Autofarm v${version}; generated by build.mjs.
local BASE = "${base}"
local LOADER_URL = "${repo}loader.lua"
local env = getgenv and getgenv() or _G
local previous = env.ClarisGrowbloxApp
assert(not previous or (not previous.job and previous.pending == 0),
    "Stop the running farm and wait for requests before loading the script again.")
local function fetch(url)
    local done, result = false, nil
    task.spawn(function()
        result = { pcall(function() return game:HttpGet(url) end) }
        done = true
    end)
    local deadline = os.clock() + 45
    while not done do
        assert(os.clock() < deadline, "Download timed out: " .. url)
        task.wait(0.05)
    end
    assert(result[1] and type(result[2]) == "string" and #result[2] > 0,
        "Could not download " .. url .. ": " .. tostring(result[2]))
    return result[2]
end
local source = fetch(BASE .. "main.lua")
local chunk, message = loadstring(source, "Claris Growblox Autofarm")
assert(chunk, message)
local windSource = fetch(BASE .. "vendor/WindUI.lua")
local windChunk, windError = loadstring(windSource, "Claris WindUI")
assert(windChunk, windError)
env.ClarisGrowbloxWindUI = windChunk()
env.ClarisGrowbloxLoaderURL = LOADER_URL
env.ClarisGrowbloxWindUIURL = BASE .. "vendor/WindUI.lua"
return chunk()
`;
const files = {
    'main.lua': bundle,
    'vendor/WindUI.lua': wind,
    'vendor/WindUI.LICENSE': license,
};
for (const [path, content] of Object.entries(files)) {
    for (const prefix of ['', `releases/${revision}/`]) {
        const target = join(root, prefix, path);
        mkdirSync(dirname(target), { recursive: true });
        if (prefix && existsSync(target) && readFileSync(target, 'utf8') !== content) {
            throw new Error(`Refusing to overwrite immutable release ${target}`);
        }
        writeFileSync(target, content);
    }
}
writeFileSync(join(root, 'loader.lua'), loader);
const manifest = {
    version, revision, base,
    files: Object.fromEntries(Object.entries(files).map(([path, content]) => [path, digest(content)])),
};
writeFileSync(join(root, 'release.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`Built v${manifest.version}, revision ${revision}`);
